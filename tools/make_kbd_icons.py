"""Draw the search keyboard's language key faces and write them as kbd_icons.h.

    make_kbd_icons.py NotoSans-SemiBold.ttf NotoSansHebrew-SemiBold.ttf NotoSansHebrew-Regular.ttf

Two faces, KEY_W x KEY_H, white on transparent, premultiplied RGBA (what the SDK's
draw_image takes): a globe and the language that is active now, "EN" or "עב". The Hebrew is
drawn as a picture because the core's own text font has no Hebrew letters. Pillow without
libraqm draws left to right, so the label is given in visual order.

Also the 26 Hebrew letters for the letter keys in Hebrew mode (the deck's keys show images
of their Latin letters, made when the keyboard is built), in the deck's key-letter color, in
the order of the a..z keys they replace.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

KEY_W, KEY_H = 110, 73          # the gap between the 123 key and z, in panel pixels
SCALE = 4                       # drawn large, then scaled down for smooth edges


def face(label, font_path):
    w, h = KEY_W * SCALE, KEY_H * SCALE
    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    white = (255, 255, 255, 255)
    # globe: a circle, the equator, two latitudes, a meridian and two curved meridians
    r = 15 * SCALE
    cx, cy = 26 * SCALE, h // 2
    lw = 2 * SCALE
    d.ellipse((cx - r, cy - r, cx + r, cy + r), outline=white, width=lw)
    d.line((cx - r, cy, cx + r, cy), fill=white, width=lw)
    for dy in (-r // 2, r // 2):
        half = int((r * r - dy * dy) ** 0.5)
        d.line((cx - half, cy + dy, cx + half, cy + dy), fill=white, width=lw)
    d.line((cx, cy - r, cx, cy + r), fill=white, width=lw)
    d.ellipse((cx - r // 2, cy - r, cx + r // 2, cy + r), outline=white, width=lw)
    # the language
    font = ImageFont.truetype(font_path, 26 * SCALE)
    box = d.textbbox((0, 0), label, font=font)
    tx = 50 * SCALE + (w - 50 * SCALE - (box[2] - box[0])) // 2 - box[0]
    ty = (h - (box[3] - box[1])) // 2 - box[1]
    d.text((tx, ty), label, font=font, fill=white)
    img = img.resize((KEY_W, KEY_H), Image.LANCZOS)
    raw = img.tobytes()
    out = bytearray(len(raw))
    for i in range(0, len(raw), 4):                     # premultiply
        a = raw[i + 3]
        out[i:i + 4] = bytes((raw[i] * a // 255, raw[i + 1] * a // 255, raw[i + 2] * a // 255, a))
    return bytes(out)


LETTER_W, LETTER_H = 48, 48
LETTER_RGB = (244, 239, 233)            # the deck's key letters
# a..z on the Israeli layout; q and w give the final pe and tsadi (no ; or . key on the deck)
HEBREW_KEYS = "שנבגקכעיןחלךצמםפףרדאוהץסטז"


# The deck's key letters: a 15 px lower-case body standing on a baseline 46 px below the
# key's top. Hebrew letters read best a little taller (16 px), on the same baseline. The
# letter image is drawn centered on a 74 px key, so its top sits 13 px below the key's.
LETTER_PX = 27                  # Noto Sans Hebrew size giving a 16 px body
LETTER_BASELINE = 46 - 13       # the baseline inside the letter image


def letter(ch, font_path):
    w, h = LETTER_W * SCALE, LETTER_H * SCALE
    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    font = ImageFont.truetype(font_path, LETTER_PX * SCALE)
    box = d.textbbox((0, 0), ch, font=font)
    # centered horizontally; the common body (HE) stands on the baseline, so descenders
    # (final kaf, final nun, qof...) reach below it as they should
    ref = d.textbbox((0, 0), "ה", font=font)
    tx = (w - (box[2] - box[0])) // 2 - box[0]
    ty = LETTER_BASELINE * SCALE - ref[3]
    d.text((tx, ty), ch, font=font, fill=LETTER_RGB + (255,))
    return premultiply(img.resize((LETTER_W, LETTER_H), Image.LANCZOS))


def premultiply(img):
    raw = img.tobytes()
    out = bytearray(len(raw))
    for i in range(0, len(raw), 4):
        a = raw[i + 3]
        out[i:i + 4] = bytes((raw[i] * a // 255, raw[i + 1] * a // 255, raw[i + 2] * a // 255, a))
    return bytes(out)


def c_array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"static const unsigned char {name}[{len(data)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def main(latin_font, hebrew_font, hebrew_regular):
    en = face("EN", latin_font)
    he = face("בע", hebrew_font)                          # "עב" in visual order
    letters = b"".join(letter(ch, hebrew_regular) for ch in HEBREW_KEYS)
    os.makedirs("out", exist_ok=True)
    with open("kbd_icons.h", "w") as f:
        f.write("/* Generated by tools/make_kbd_icons.py: the search keyboard's language key,\n"
                " * premultiplied RGBA, drawn with Noto Sans and Noto Sans Hebrew (SIL OFL 1.1). */\n"
                "#ifndef KBD_ICONS_H\n#define KBD_ICONS_H\n"
                f"#define KBD_KEY_W {KEY_W}\n#define KBD_KEY_H {KEY_H}\n")
        f.write(c_array("kbd_face_en", en))
        f.write(c_array("kbd_face_he", he))
        f.write(f"#define KBD_LETTER_W {LETTER_W}\n#define KBD_LETTER_H {LETTER_H}\n"
                "/* 26 images, one per a..z key, KBD_LETTER_W x KBD_LETTER_H each. */\n")
        f.write(c_array("kbd_letters", letters))
        f.write("#endif\n")
    Image.frombytes("RGBA", (KEY_W, KEY_H), he).save("out/kbd_face_he.png")
    Image.frombytes("RGBA", (KEY_W, KEY_H), en).save("out/kbd_face_en.png")
    print("wrote kbd_icons.h and out/kbd_face_{en,he}.png")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
